import { useState, type FormEvent } from 'react'

import { ApiError, api } from '../api/client'
import type { Patient, PatientInput, Sex } from '../api/types'
import { Icon } from './Icon'
import { Modal } from './Modal'
import { ErrorBanner, Notice } from './ui'

const SEX_OPTIONS: { value: Sex; label: string }[] = [
  { value: 'unknown', label: 'Not recorded' },
  { value: 'female', label: 'Female' },
  { value: 'male', label: 'Male' },
  { value: 'other', label: 'Other' },
]

export function PatientForm({
  patient,
  onClose,
  onSaved,
}: {
  patient?: Patient
  onClose: () => void
  onSaved: (patient: Patient) => void
}) {
  const editing = Boolean(patient)
  const [fullName, setFullName] = useState(patient?.full_name ?? '')
  const [phone, setPhone] = useState(patient?.phone ?? '')
  const [email, setEmail] = useState(patient?.email ?? '')
  const [dateOfBirth, setDateOfBirth] = useState(patient?.date_of_birth ?? '')
  const [ageYears, setAgeYears] = useState(
    patient?.age_years === null || patient?.age_years === undefined
      ? ''
      : String(patient.age_years),
  )
  const [sex, setSex] = useState<Sex>(patient?.sex ?? 'unknown')
  const [notes, setNotes] = useState(patient?.notes ?? '')
  const [saving, setSaving] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [duplicates, setDuplicates] = useState<Patient[]>([])

  const input: PatientInput = {
    full_name: fullName.trim(),
    phone: phone.trim(),
    email: email.trim(),
    date_of_birth: dateOfBirth || null,
    age_years: dateOfBirth ? null : ageYears ? Number(ageYears) : null,
    sex,
    notes,
  }

  async function save(confirmDuplicate = false) {
    if (!fullName.trim()) return
    setSaving(true)
    setError(null)
    try {
      const saved = patient
        ? await api.updatePatient(patient.id, input)
        : await api.createPatient(input, confirmDuplicate)
      onSaved(saved)
    } catch (caught) {
      if (caught instanceof ApiError && caught.status === 409) {
        setDuplicates(caught.payload.duplicates ?? [])
        setError(caught.message)
      } else {
        setError(
          caught instanceof ApiError
            ? caught.message
            : 'Could not save the patient record.',
        )
      }
    } finally {
      setSaving(false)
    }
  }

  function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    void save(false)
  }

  return (
    <Modal
      title={editing ? 'Edit patient' : 'Register a patient'}
      subtitle="The permanent patient ID is generated by the application and never changes."
      onClose={onClose}
      footer={
        <>
          <button type="button" className="button button--ghost" onClick={onClose}>
            Cancel
          </button>
          {duplicates.length > 0 ? (
            <button
              type="button"
              className="button button--danger"
              onClick={() => void save(true)}
              disabled={saving}
            >
              {saving ? 'Saving…' : 'Create anyway'}
            </button>
          ) : (
            <button
              type="submit"
              form="patient-form"
              className="button button--primary"
              disabled={saving}
            >
              {saving ? 'Saving…' : editing ? 'Save changes' : 'Register patient'}
            </button>
          )}
        </>
      }
    >
      <form id="patient-form" className="form" onSubmit={submit}>
        <div className="form-grid">
          <label className="field">
            <span>Full name</span>
            <input
              value={fullName}
              onChange={(event) => setFullName(event.target.value)}
              placeholder="e.g. Aarav Sharma"
              autoComplete="off"
              required
            />
          </label>
          <label className="field">
            <span>Phone number</span>
            <input
              value={phone}
              onChange={(event) => setPhone(event.target.value)}
              placeholder="+91 98765 43210"
              inputMode="tel"
              autoComplete="off"
            />
            <small>Used to find a returning patient and to warn about duplicates.</small>
          </label>
          <label className="field">
            <span>Email (optional)</span>
            <input
              type="email"
              value={email}
              onChange={(event) => setEmail(event.target.value)}
              placeholder="optional"
            />
          </label>
          <label className="field">
            <span>Sex</span>
            <select value={sex} onChange={(event) => setSex(event.target.value as Sex)}>
              {SEX_OPTIONS.map((option) => (
                <option key={option.value} value={option.value}>
                  {option.label}
                </option>
              ))}
            </select>
          </label>
          <label className="field">
            <span>Date of birth (optional)</span>
            <input
              type="date"
              value={dateOfBirth}
              max={new Date().toISOString().slice(0, 10)}
              onChange={(event) => {
                setDateOfBirth(event.target.value)
                if (event.target.value) setAgeYears('')
              }}
            />
          </label>
          <label className="field">
            <span>Age (optional, if DOB unknown)</span>
            <input
              type="number"
              min={0}
              max={130}
              value={ageYears}
              onChange={(event) => {
                setAgeYears(event.target.value)
                if (event.target.value) setDateOfBirth('')
              }}
              placeholder="years"
            />
          </label>
        </div>

        <label className="field">
          <span>Notes (optional)</span>
          <textarea
            rows={3}
            value={notes}
            onChange={(event) => setNotes(event.target.value)}
            placeholder="Referral, clinical context, or anything the operator should know."
          />
        </label>

        {error && <ErrorBanner message={error} />}

        {duplicates.length > 0 && (
          <Notice tone="warn" icon="alert">
            <strong>A patient with this phone number already exists.</strong>
            <div className="duplicate-list">
              {duplicates.map((match) => (
                <div key={match.id} className="duplicate-row">
                  <span>
                    <strong>{match.full_name}</strong> · {match.patient_id}
                  </span>
                  <span className="muted small">
                    {match.phone || 'no phone'} · {match.session_count} session
                    {match.session_count === 1 ? '' : 's'}
                  </span>
                </div>
              ))}
            </div>
            <span className="small">
              Open the existing profile instead if this is the same person. If it is a
              different person who shares the number, confirm below.
            </span>
          </Notice>
        )}

        <p className="muted small">
          <Icon name="shield" size={14} /> Patient information is available to authenticated
          operators of this installation.
        </p>
      </form>
    </Modal>
  )
}
