import { useState } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { zodResolver } from '@hookform/resolvers/zod'
import { useForm } from 'react-hook-form'

import { ApiError } from '@/shared/api/http'
import { patientsApi } from '@/features/patients/api'
import type { Patient, Sex } from '@/shared/types'
import { Icon } from '@/shared/icons/Icon'
import { Modal } from '@/shared/ui/Modal'
import { ErrorBanner } from '@/shared/ui'
import {
  patientDefaults,
  patientSchema,
  patientToInput,
  type PatientFormValues,
} from '../model/patientSchema'
import { DuplicatePatientNotice } from './DuplicatePatientNotice'

const SEX_OPTIONS: { value: Sex; label: string }[] = [
  { value: 'unknown', label: 'Not recorded' },
  { value: 'female', label: 'Female' },
  { value: 'male', label: 'Male' },
  { value: 'other', label: 'Other' },
]

export function PatientForm({
  patient,
  onClose,
  onSaved,
}: {
  patient?: Patient
  onClose: () => void
  onSaved: (patient: Patient) => void
}) {
  const editing = Boolean(patient)
  const [duplicates, setDuplicates] = useState<Patient[]>([])
  const [error, setError] = useState<string | null>(null)
  const queryClient = useQueryClient()

  const {
    register,
    handleSubmit,
    setValue,
    formState: { errors },
  } = useForm<PatientFormValues>({
    resolver: zodResolver(patientSchema),
    defaultValues: patientDefaults(patient),
  })

  const mutation = useMutation({
    mutationFn: ({ values, confirmDuplicate }: { values: PatientFormValues; confirmDuplicate: boolean }) => {
      const input = patientToInput(values)
      return patient
        ? patientsApi.update(patient.id, input)
        : patientsApi.create(input, confirmDuplicate)
    },
    onSuccess: (saved) => {
      void queryClient.invalidateQueries()
      onSaved(saved)
    },
    onError: (caught) => {
      if (caught instanceof ApiError && caught.status === 409) {
        setDuplicates(caught.payload.duplicates ?? [])
        setError(caught.message)
      } else {
        setError(caught instanceof ApiError ? caught.message : 'Could not save the patient record.')
      }
    },
  })

  function save(values: PatientFormValues, confirmDuplicate = false) {
    setError(null)
    setDuplicates([])
    mutation.mutate({ values, confirmDuplicate })
  }

  const saving = mutation.isPending

  return (
    <Modal
      title={editing ? 'Edit patient' : 'Register a patient'}
      subtitle="The permanent patient ID is generated by the application and never changes."
      onClose={onClose}
      footer={
        <>
          <button type="button" className="button button--ghost" onClick={onClose}>
            Cancel
          </button>
          {duplicates.length > 0 ? (
            <button
              type="button"
              className="button button--danger"
              onClick={() => void handleSubmit((values) => save(values, true))()}
              disabled={saving}
            >
              {saving ? 'Saving…' : 'Create anyway'}
            </button>
          ) : (
            <button
              type="submit"
              form="patient-form"
              className="button button--primary"
              disabled={saving}
            >
              {saving ? 'Saving…' : editing ? 'Save changes' : 'Register patient'}
            </button>
          )}
        </>
      }
    >
      <form
        id="patient-form"
        className="form"
        onSubmit={(event) => void handleSubmit((values) => save(values))(event)}
        noValidate
      >
        <div className="form-grid">
          <label className="field">
            <span>Full name</span>
            <input
              {...register('full_name')}
              placeholder="e.g. Aarav Sharma"
              autoComplete="off"
              aria-invalid={Boolean(errors.full_name)}
            />
            {errors.full_name && <small className="field__error">{errors.full_name.message}</small>}
          </label>
          <label className="field">
            <span>Phone number</span>
            <input
              {...register('phone')}
              placeholder="+91 98765 43210"
              inputMode="tel"
              autoComplete="off"
              aria-invalid={Boolean(errors.phone)}
            />
            {errors.phone ? (
              <small className="field__error">{errors.phone.message}</small>
            ) : (
              <small>Used to find a returning patient and to warn about duplicates.</small>
            )}
          </label>
          <label className="field">
            <span>Email (optional)</span>
            <input
              {...register('email')}
              type="email"
              placeholder="optional"
              aria-invalid={Boolean(errors.email)}
            />
            {errors.email && <small className="field__error">{errors.email.message}</small>}
          </label>
          <label className="field">
            <span>Sex</span>
            <select {...register('sex')}>
              {SEX_OPTIONS.map((option) => (
                <option key={option.value} value={option.value}>
                  {option.label}
                </option>
              ))}
            </select>
          </label>
          <label className="field">
            <span>Date of birth (optional)</span>
            <input
              {...register('date_of_birth', {
                onChange: (event) => {
                  if (event.target.value) {
                    setValue('age_years', '', { shouldValidate: true })
                  }
                },
              })}
              type="date"
              max={new Date().toISOString().slice(0, 10)}
              aria-invalid={Boolean(errors.date_of_birth)}
            />
            {errors.date_of_birth && (
              <small className="field__error">{errors.date_of_birth.message}</small>
            )}
          </label>
          <label className="field">
            <span>Age (optional, if DOB unknown)</span>
            <input
              {...register('age_years', {
                onChange: (event) => {
                  if (event.target.value) {
                    setValue('date_of_birth', '', { shouldValidate: true })
                  }
                },
              })}
              type="number"
              min={0}
              max={130}
              placeholder="years"
              aria-invalid={Boolean(errors.age_years)}
            />
            {errors.age_years && (
              <small className="field__error">{errors.age_years.message}</small>
            )}
          </label>
        </div>

        <label className="field">
          <span>Notes (optional)</span>
          <textarea
            {...register('notes')}
            rows={3}
            placeholder="Referral, clinical context, or anything the operator should know."
          />
        </label>

        {error && <ErrorBanner message={error} />}

        <DuplicatePatientNotice duplicates={duplicates} />

        <p className="muted small">
          <Icon name="shield" size={14} /> Patient information is available to authenticated
          operators of this installation.
        </p>
      </form>
    </Modal>
  )
}
